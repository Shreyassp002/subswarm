export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** The lit dots of a string, as [x, y] pairs in dot units, with one dot between glyphs. */
export function dots(text: string) {
  const out: [number, number][] = [];
  [...text.toUpperCase()].forEach((char, index) => {
    const glyph = GLYPHS[char] ?? GLYPHS[" "];
    glyph.forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit === "1") out.push([index * (GLYPH_W + 1) + x, y]);
      });
    });
  });
  return out;
}

/** Width of a string in dots. */
export const width = (text: string) => Math.max(0, text.length * (GLYPH_W + 1) - 1);
